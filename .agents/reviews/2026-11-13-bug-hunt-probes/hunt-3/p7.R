cls <- function(e) tryCatch({e; "ok"}, error=function(e) class(e)[1])
l1 <- c("caf\xe9", "na\xefve", "z\xfcrich"); Encoding(l1) <- "latin1"
df <- data.frame(i=1:3, d=c(1.5,NA,2^60), s=l1, f=factor(l1), dt=as.Date(c(0,NA,1e4)), t=as.POSIXct(c(0,NA,1e9), tz="UTC"))
names(df)[3] <- l1[1]; df$l <- list(1:3, list(x=l1, y=I(2)), setNames(1:2, l1[1:2])); df$alt <- as.character(1:3)
x <- list(a=df, b=setNames(as.list(1:3), l1), c=as.character(1:5), d=1:10, e=list(NULL, list(), I("x")), f=factor(as.character(5:1)))
bad <- x; bad$e[[4]] <- sum; by <- "a\xff"; Encoding(by) <- "bytes"; bad2 <- x; bad2$b <- setNames(1:2, c("ok", by))
bad3 <- df; bad3$z <- list(1, 2, as.POSIXlt("2020-01-01"))
r0 <- list(json_write(x), json_write(x, pretty=TRUE), json_write_raw(x), json_write_ndjson(df), json_write_ndjson(x), json_write_ndjson_raw(df), json_write(x, auto_unbox=FALSE))
e0 <- c(cls(json_write(bad)), cls(json_write(bad2)), cls(json_write(bad3)), cls(json_write_ndjson(bad3)), cls(json_write_ndjson(bad)))
print(e0)
gctorture(TRUE)
r1 <- list(json_write(x), json_write(x, pretty=TRUE), json_write_raw(x), json_write_ndjson(df), json_write_ndjson(x), json_write_ndjson_raw(df), json_write(x, auto_unbox=FALSE))
e1 <- c(cls(json_write(bad)), cls(json_write(bad2)), cls(json_write(bad3)), cls(json_write_ndjson(bad3)), cls(json_write_ndjson(bad)))
p1 <- json_parse(r0[[1]]); p2 <- json_parse(r0[[1]], data_frame=TRUE); p3 <- json_parse_ndjson(r0[[4]], data_frame=TRUE)
gctorture(FALSE)
cat("identical under gctorture:", identical(r0, r1), identical(e0, e1), identical(p1, json_parse(r0[[1]])), identical(p2, json_parse(r0[[1]], data_frame=TRUE)), "\n")
cat(r0[[1]], "\n")
